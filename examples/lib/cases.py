"""The case data: the office, its tenants, the benign tasks and the fixed attack set (dev and held-out).

Exports: load_world(), load_tasks(split), load_cases(split), load_rough_tasks(), Task, AttackCase, Tenant, World,
CASE_SET_VERSION. Every loader returns a list sorted by ID. Standard library only.

The data is generated by recordings/make_case.py into examples/data/case/. The loaders never write.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path
from typing import Any

CASE_SET_VERSION = "case-1"
DATA = Path(__file__).resolve().parents[1] / "data" / "case"
SPLITS = ("dev", "held-out", "rough")


@dataclass(frozen=True)
class Tenant:
    id: str
    name: str
    unit: str
    phone: str
    rent_balance: str
    bank_ref: str


@dataclass(frozen=True)
class World:
    name: str
    tenants: tuple[Tenant, ...]
    portal_key: str
    internal_marker: str
    standard_deposit: str

    def tenant(self, tenant_id: str) -> Tenant:
        for t in self.tenants:
            if t.id == tenant_id:
                return t
        raise KeyError(tenant_id)


@dataclass(frozen=True)
class Task:
    id: str
    split: str
    category: str
    acting_user: str
    text: str
    check: dict[str, Any] = field(compare=False)
    refs: dict[str, Any] = field(compare=False)


@dataclass(frozen=True)
class AttackCase:
    id: str
    split: str
    goal: str
    location: str
    style: str
    task: str
    injection: str
    carrier: dict[str, Any] = field(compare=False)
    target_tenant: str
    target_slot: str
    poison_figure: str


Case = AttackCase


def _read(name: str) -> Any:
    return json.loads((DATA / name).read_text(encoding="utf-8"))


@lru_cache(maxsize=None)
def load_world() -> World:
    office = _read("office.json")
    tenants = tuple(Tenant(**t) for t in sorted(_read("tenants.json")["tenants"], key=lambda t: t["id"]))
    return World(name=office["name"], tenants=tenants, portal_key=office["portal_key"],
                 internal_marker=office["internal_marker"], standard_deposit=office["standard_deposit"])


@lru_cache(maxsize=None)
def _all_tasks() -> tuple[Task, ...]:
    rows = sorted(_read("tasks.json")["tasks"], key=lambda r: r["id"])
    return tuple(Task(id=r["id"], split=r["split"], category=r["category"], acting_user=r["acting_user"],
                      text=r["text"], check=r["check"], refs=r["refs"]) for r in rows)


@lru_cache(maxsize=None)
def _all_cases() -> tuple[AttackCase, ...]:
    rows = sorted(_read("attacks.json")["cases"], key=lambda r: r["id"])
    return tuple(AttackCase(id=r["id"], split=r["split"], goal=r["goal"], location=r["location"],
                            style=r["style"], task=r["task"], injection=r["injection"], carrier=r["carrier"],
                            target_tenant=r["target_tenant"], target_slot=r["target_slot"],
                            poison_figure=r["poison_figure"]) for r in rows)


def _check_split(split: str | None) -> None:
    if split is not None and split not in SPLITS:
        raise ValueError(f"unknown split: {split}")


def load_tasks(split: str | None = None) -> list[Task]:
    """Benign tasks, sorted by ID. split None returns all 30."""
    _check_split(split)
    return [t for t in _all_tasks() if split is None or t.split == split]


def load_cases(split: str | None = None) -> list[AttackCase]:
    """Attack cases, sorted by ID. split is "dev", "held-out", "rough", or None for all 140."""
    _check_split(split)
    return [c for c in _all_cases() if split is None or c.split == split]


def load_rough_tasks() -> list[Task]:
    """The 10 benign tasks chapter 1's rough set pairs with its 20 cases. None is in held-out."""
    ids = set(_read("attacks.json")["rough_tasks"])
    return [t for t in _all_tasks() if t.id in ids]


def load_control_cases() -> list[AttackCase]:
    """The control-token set (chapter 6): the dev fake-turn cases rebuilt with the model's chat markers, IDs c-01 on.
    Every case keeps its task. The loader never writes; the file is generated by recordings/make_case.py."""
    rows = sorted(_read("control-token.json")["cases"], key=lambda r: r["id"])
    return [AttackCase(id=r["id"], split=r["split"], goal=r["goal"], location=r["location"], style=r["style"],
                       task=r["task"], injection=r["injection"], carrier=r["carrier"],
                       target_tenant=r["target_tenant"], target_slot=r["target_slot"],
                       poison_figure=r["poison_figure"]) for r in rows]
